#!/usr/bin/env node
// Sync the .cursor/rules/*.mdc → SKILL.md "drift state" file.
//
// The skills under `packages/claude-plugin/skills/*/SKILL.md` are
// human-authored summaries of the canonical `.cursor/rules/*.mdc`
// rules. Auto-regeneration would lose nuance — instead, this script
// pins a content hash of each rule file, and `check-skills-sync.mjs`
// fails CI when a rule changes without an author re-running this
// script (i.e., without acknowledging that the SKILL.md still
// accurately summarizes the rule).
//
// Usage:
//   node scripts/sync-skills.mjs        — recompute hashes, write state file
//   pnpm run sync:skills                — same via root script
//
// The hash file at `scripts/skills-sync-state.json` is committed.

import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, "..");
const RULES_DIR = join(REPO_ROOT, ".cursor", "rules");
const STATE_PATH = join(__dirname, "skills-sync-state.json");

async function main() {
  const ruleFiles = (await readdir(RULES_DIR)).filter((f) => f.endsWith(".mdc")).sort();

  const previous = await loadState(STATE_PATH);
  const next = { rules: {} };
  const changes = [];

  for (const file of ruleFiles) {
    const path = join(RULES_DIR, file);
    const text = await readFile(path, "utf8");
    const hash = createHash("sha256").update(text).digest("hex");
    next.rules[file] = hash;
    const prevHash = previous.rules?.[file];
    if (prevHash === undefined) {
      changes.push({ file, kind: "added" });
    } else if (prevHash !== hash) {
      changes.push({ file, kind: "changed" });
    }
  }

  for (const file of Object.keys(previous.rules ?? {})) {
    if (!Object.hasOwn(next.rules, file)) {
      changes.push({ file, kind: "removed" });
    }
  }

  await writeFile(
    STATE_PATH,
    JSON.stringify(
      {
        comment:
          "Generated by `pnpm run sync:skills`. Hashes pin the .cursor/rules/*.mdc content the SKILL.md summaries were last reviewed against. Do not edit by hand — re-run `pnpm run sync:skills` after editing any rule.",
        rules: next.rules,
      },
      null,
      2,
    ) + "\n",
  );

  if (changes.length === 0) {
    console.log("sync:skills: no changes — state file unchanged.");
    return;
  }

  console.log(
    `sync:skills: updated state for ${ruleFiles.length} rule${ruleFiles.length === 1 ? "" : "s"}.`,
  );
  for (const c of changes) {
    const symbol = c.kind === "added" ? "+" : c.kind === "removed" ? "-" : "~";
    console.log(`  ${symbol} ${c.file} (${c.kind})`);
  }
  console.log(
    "\nReview the SKILL.md summaries under packages/claude-plugin/skills/ to confirm they still accurately reflect the rules. Commit the updated state file.",
  );
}

async function loadState(path) {
  try {
    const text = await readFile(path, "utf8");
    return JSON.parse(text);
  } catch (err) {
    if (err.code === "ENOENT") return { rules: {} };
    throw err;
  }
}

main().catch((err) => {
  console.error("sync:skills failed:", err.message);
  process.exit(1);
});
