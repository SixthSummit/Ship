/**
 * `ng generate @sixthsummit/ship-angular:module <name>` schematic.
 *
 * Creates an app-owned feature module under `src/app/modules/<name>/` with:
 *
 * - `module.json` — manifest (name, description, version, dependencies)
 * - `routes.ts` — exports `<name>Routes: Routes` with a placeholder page
 * - `index.ts` — re-exports the routes
 * - `MODULE.md` — public-surface documentation following framework convention
 * - `components/.gitkeep`, `pages/.gitkeep`
 *
 * Optionally injects a lazy-load entry into `src/app/app.routes.ts` so the
 * module's routes are wired immediately.
 */
import { strings } from '@angular-devkit/core';
import {
  apply,
  chain,
  mergeWith,
  move,
  type Rule,
  template as renderTemplates,
  type SchematicContext,
  SchematicsException,
  type Tree,
  url,
} from '@angular-devkit/schematics';

interface ModuleOptions {
  name: string;
  description?: string;
  dependencies?: string;
  addRoute?: boolean;
  routePath?: string;
  guarded?: boolean;
}

export function module(options: ModuleOptions): Rule {
  if (!options.name) {
    throw new SchematicsException('ship-angular:module — name is required.');
  }
  const name = strings.dasherize(options.name);
  const description = options.description ?? `A ShipAngular feature module: ${name}`;
  const dependencies = (options.dependencies ?? '')
    .split(',')
    .map(s => s.trim())
    .filter(Boolean);
  const routePath = options.routePath ?? name;
  const guarded = options.guarded ?? false;

  return chain([
    scaffoldModuleFiles({
      name,
      description,
      dependencies,
      routePath,
      guarded,
    }),
    options.addRoute === false ? noop() : injectRouteIntoApp(name, routePath, guarded),
    logSummary(name),
  ]);
}

interface ScaffoldArgs {
  name: string;
  description: string;
  dependencies: readonly string[];
  routePath: string;
  guarded: boolean;
}

function scaffoldModuleFiles(args: ScaffoldArgs): Rule {
  return (tree: Tree) => {
    const target = `src/app/modules/${args.name}`;
    if (tree.getDir(target).subfiles.length > 0 || tree.getDir(target).subdirs.length > 0) {
      throw new SchematicsException(
        `ship-angular:module — src/app/modules/${args.name}/ already exists. Choose a different name or remove the existing directory first.`
      );
    }
    const templateSource = apply(url('./files'), [
      renderTemplates({
        ...strings,
        name: args.name,
        description: args.description,
        dependencies: JSON.stringify(args.dependencies),
        routePath: args.routePath,
        guarded: args.guarded,
        guardImport: args.guarded ? `import { authGuard } from '@sixthsummit/ship-angular';` : '',
        canActivate: args.guarded ? `canActivate: [authGuard],` : '',
      }),
      move(target),
    ]);
    return mergeWith(templateSource);
  };
}

function injectRouteIntoApp(name: string, routePath: string, _guarded: boolean): Rule {
  return (tree: Tree, context: SchematicContext) => {
    const candidates = ['/src/app/app.routes.ts', '/src/app/app-routing.module.ts'];
    const target = candidates.find(p => tree.exists(p));
    if (!target) {
      context.logger.warn(
        `ship-angular:module — couldn't find app.routes.ts; skipping auto route injection. Manually wire ${name}Routes from modules/${name}/routes.`
      );
      return tree;
    }
    const source = tree.readText(target);
    const importStmt = `import { ${strings.camelize(name)}Routes } from './modules/${name}/routes';`;
    if (source.includes(importStmt) || source.includes(`from './modules/${name}/routes'`)) {
      // Already wired — nothing to do.
      return tree;
    }
    let next = source;
    // Add the import at the top, after the last existing import line.
    const importMatch = next.match(/^(?:import [^\n]+\n)+/);
    if (importMatch) {
      const last = importMatch[0];
      next = next.replace(last, `${last}${importStmt}\n`);
    } else {
      next = `${importStmt}\n${next}`;
    }
    // Inject the spread into the Routes array.
    const routesRegex = /export const routes(?:\s*:\s*Routes)?\s*=\s*\[/;
    const m = next.match(routesRegex);
    if (m) {
      const idx = m.index! + m[0].length;
      const insertion = `\n  // ${name} module — generated by ship-angular:module\n  ...${strings.camelize(name)}Routes,\n`;
      next = next.slice(0, idx) + insertion + next.slice(idx);
    } else {
      context.logger.warn(
        `ship-angular:module — couldn't find a 'export const routes' array in ${target}; route import added but spread not injected. Wire manually.`
      );
    }
    tree.overwrite(target, next);
    context.logger.info(`✓ Wired ${name}Routes into ${target} (mounted at /${routePath}).`);
    return tree;
  };
}

function noop(): Rule {
  return (tree: Tree) => tree;
}

function logSummary(name: string): Rule {
  return (_tree: Tree, context: SchematicContext) => {
    context.logger.info(`✓ ship-angular:module — created src/app/modules/${name}/`);
    context.logger.info(
      `  Next: edit src/app/modules/${name}/MODULE.md, add components/pages, and run the project quality gates.`
    );
  };
}
