/** How an operation's declared publications are delivered. */
export function publicationDelivery(operation: AnyOperation): PublicationDelivery {
  return operation.transaction === "none" ? "immediate" : "outbox";
}

/**
 * Every write operation that publishes needs the framework dispatcher mounted
 * with each of its channels listed; otherwise recorded intents would never be
 * published.
 */
export function checkRealtimePublicationDispatch(
  appId: string,
  modules: readonly AnyModule[],
  diagnostics: ApplicationDiagnostic[],
): void {
  const dispatched = new Set<string>();
  const publishers: { readonly module: AnyModule; readonly operation: AnyOperation }[] = [];
  for (const module of modules) {
    for (const operation of module.operations) {
      if (operation.publishes.length > 0 && operation.transaction === "write") {
        publishers.push({ module, operation });
      }
      const role = describeOutboxOperation(operation);
      if (role?.role === "dispatcher" && role.outboxId === REALTIME_PUBLICATION_OUTBOX_ID) {
        for (const intentId of role.intentIds) dispatched.add(intentId);
      }
    }
  }
  for (const site of publishers) {
    for (const channel of [...site.operation.publishes].sort((left, right) =>
      left.id.localeCompare(right.id),
    )) {
      if (dispatched.has(channel.id)) continue;
      diagnostics.push({
        code: "SHIP_OPERATION_PUBLISH_DISPATCHER_MISSING",
        severity: "error",
        message: `write operation ${JSON.stringify(site.operation.id)} publishes to channel ${JSON.stringify(channel.id)} but no realtime publication dispatcher covering it is composed into the application`,
        hint: `Mount defineRealtimePublicationModule({ channels: [...] }) once with ${JSON.stringify(channel.id)} listed so recorded publication intents are published after commit.`,
        appId,
        moduleId: site.module.id,
        operationId: site.operation.id,
        providerId: channel.publication.id,
        path: "publishes",
      });
    }
  }
}

function assertChannels(channels: unknown): asserts channels is readonly AnyChannel[] {
  if (!Array.isArray(channels) || channels.length === 0 || !channels.every(isChannel)) {
    throw new RealtimeError(
      "SHIP_REALTIME_CHANNEL_INVALID",
      "realtime publication requires a non-empty list of channels created by defineChannel()",
    );
  }
  const ids = new Set<string>();
  for (const channel of channels) {
    if (ids.has(channel.id)) {
      throw new RealtimeError(
        "SHIP_REALTIME_CHANNEL_INVALID",
        `channel ${JSON.stringify(channel.id)} is listed more than once`,
        { channelId: channel.id },
      );
    }
    ids.add(channel.id);
  }
}

