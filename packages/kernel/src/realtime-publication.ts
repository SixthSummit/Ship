export interface DispatchRealtimePublicationsOptions {
  /** Defaults to `systemActor({ id: REALTIME_PUBLICATION_RUNNER_ACTOR_ID })`. */
  readonly actor?: SystemOperationActor;
  readonly requestId?: string;
  readonly signal?: AbortSignal;
}

type AnyExecutor = ApplicationExecutor<CompiledApplication<string, readonly AnyModule[]>>;

/**
 * Performs one dispatch pass of `ship-realtime.publication.dispatch` through
 * the executor and returns what it claimed, completed, retried and
 * dead-lettered. This is the only dispatch path: the standalone runner, the
 * declared dispatch job and test helpers all call it, so a consumer that
 * starts with the loop and later adopts jobs changes nothing about delivery.
 * A run that does not succeed (the module is not mounted, the backend
 * refused) is `SHIP_REALTIME_DISPATCH_FAILED`.
 */
export async function dispatchRealtimePublications(
  executor: AnyExecutor,
  options: DispatchRealtimePublicationsOptions = {},
): Promise<OutboxDispatchResult> {
  let result: Awaited<ReturnType<AnyExecutor["run"]>>;
  try {
    result = await executor.run(REALTIME_PUBLICATION_DISPATCH_OPERATION_ID as never, {} as never, {
      actor: options.actor ?? systemActor({ id: REALTIME_PUBLICATION_RUNNER_ACTOR_ID }),
      ...(options.requestId !== undefined ? { requestId: options.requestId } : {}),
      ...(options.signal ? { signal: options.signal } : {}),
    });
  } catch (error) {
    if (!(error instanceof OperationExecutionError)) throw error;
    throw new RealtimeError(
      "SHIP_REALTIME_DISPATCH_FAILED",
      error.code === "SHIP_OPERATION_NOT_FOUND"
        ? `realtime publication dispatch is not composed into the application; mount defineRealtimePublicationModule()`
        : `realtime publication dispatch failed with ${error.code}`,
      { cause: error },
    );
  }
  if (!result.ok) {
    throw new RealtimeError(
      "SHIP_REALTIME_DISPATCH_FAILED",
      `realtime publication dispatch failed with ${result.error.code}: ${result.error.message}`,
    );
  }
  return result.data as OutboxDispatchResult;
}

