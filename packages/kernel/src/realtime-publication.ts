export { REALTIME_PUBLICATION_MODULE_ID };
/** The fixed id of the framework-owned publication outbox. */
export const REALTIME_PUBLICATION_OUTBOX_ID = "ship-realtime.publication";
/** The dispatcher operation every runner executes; generated by {@link defineRealtimePublicationDispatcher}. */
export const REALTIME_PUBLICATION_DISPATCH_OPERATION_ID = `${REALTIME_PUBLICATION_OUTBOX_ID}.dispatch`;
/** System actor the framework runners dispatch as when the caller names none. */
export const REALTIME_PUBLICATION_RUNNER_ACTOR_ID = "ship.realtime.dispatcher";

const DEFAULT_RETENTION = Object.freeze({
  completedMs: 24 * 60 * 60 * 1000,
  deadLetteredMs: 30 * 24 * 60 * 60 * 1000,
});
const DEFAULT_BATCH_SIZE = 100;
const DEFAULT_LEASE_MS = 30_000;
const DEFAULT_ATTEMPTS = 8;
const DEFAULT_BACKOFF = Object.freeze({ initialMs: 250, multiplier: 2, maxMs: 60_000 });

/**
 * The durable shape of one publication: the scope key derived from an
 * authentic scope when the intent was recorded, and the payload already
 * validated by the channel schema. The intent id is the channel id, so the
 * graph shows which channel a stored intent will publish to.
 */
export const realtimePublicationIntentSchema = objectSchema({
  scopeKey: stringSchema({ minLength: 1 }),
  payload: jsonValueSchema(),
});

export type RealtimePublicationIntent = {
  readonly scopeKey: string;
  readonly payload: unknown;
};

/** A channel publication token viewed as the effect its intent performs. */
export type RealtimePublicationEffect = EffectDependencyToken<ChannelPublisher<AnyChannel>>;

export type RealtimePublicationIntents = Readonly<
  Record<
    string,
    OutboxIntentDefinition<typeof realtimePublicationIntentSchema, RealtimePublicationEffect>
  >
>;

export type RealtimePublicationOutbox = Outbox<
  typeof REALTIME_PUBLICATION_OUTBOX_ID,
  RealtimePublicationIntents
>;

/** Delivery mode of an operation's declared publications, as projected into the graph. */
export type PublicationDelivery = "immediate" | "outbox";

/**
 * Framework-owned durable outbox for realtime publication. A write operation
 * that declares `publishes` records one intent per `publish()` call in its
 * own transaction, so the intent commits or rolls back with the business
 * change. The dispatcher publishes afterwards: delivery is eventual, and a
 * subscriber may observe the event some time after the commit. Delivery is
 * at-least-once; a subscriber may see one publication twice.
 */
export function defineRealtimePublicationOutbox(
  channels: readonly AnyChannel[],
  options: {
    readonly retention?: OutboxRetention;
    /** Expected durable publications per second; see `OutboxDefinition.expectedRatePerSecond`. */
    readonly expectedRatePerSecond?: number;
  } = {},
): RealtimePublicationOutbox {
  assertChannels(channels);
  const intents: Record<string, RealtimePublicationIntents[string]> = {};
  for (const channel of [...channels].sort((left, right) => left.id.localeCompare(right.id))) {
    intents[channel.id] = outboxIntent({
      payload: realtimePublicationIntentSchema,
      effect: channel.publication as unknown as RealtimePublicationEffect,
      perform: ({ effect, payload }) =>
        publishChannelKey(effect, payload.scopeKey, payload.payload),
    });
  }
  return defineOutbox({
    id: REALTIME_PUBLICATION_OUTBOX_ID,
    retention: options.retention ?? DEFAULT_RETENTION,
    ...(options.expectedRatePerSecond !== undefined
      ? { expectedRatePerSecond: options.expectedRatePerSecond }
      : {}),
    intents: Object.freeze(intents) as RealtimePublicationIntents,
  });
}

export interface RealtimePublicationDispatcherOptions {
  readonly batchSize?: number;
  readonly lease?: { readonly ms: number };
  readonly retry?: { readonly attempts: number; readonly backoff: OutboxBackoff };
  /** Declared dispatch cadence per process; see `OutboxDispatcherOptions.roundsPerSecond`. */
  readonly roundsPerSecond?: number;
  readonly clock?: () => Date;
}

/**
 * Generates `ship-realtime.publication.dispatch` plus its dead-letter
 * operations. The dispatcher is a `transaction: "none"` operation that binds
 * every channel's immediate publication token and declares `publishes` for
 * all of them, so the graph shows it as the process that performs every
 * durable publication.
 */
export function defineRealtimePublicationDispatcher(
  outbox: RealtimePublicationOutbox,
  options: RealtimePublicationDispatcherOptions = {},
): OutboxDispatcher<typeof REALTIME_PUBLICATION_OUTBOX_ID, RealtimePublicationIntents> {
  return defineOutboxDispatcher(outbox, {
    batchSize: options.batchSize ?? DEFAULT_BATCH_SIZE,
    lease: options.lease ?? { ms: DEFAULT_LEASE_MS },
    retry: options.retry ?? { attempts: DEFAULT_ATTEMPTS, backoff: DEFAULT_BACKOFF },
    deadLetter: true,
    ...(options.roundsPerSecond !== undefined ? { roundsPerSecond: options.roundsPerSecond } : {}),
    ...(options.clock ? { clock: options.clock } : {}),
  });
}

export interface RealtimePublicationModuleOptions extends RealtimePublicationDispatcherOptions {
  /** Every channel the application publishes to, immediately or durably. */
  readonly channels: readonly AnyChannel[];
  /** The publish-only backend every channel publisher is bound to. */
  readonly realtime: RealtimePublishBackend;
  /** Durable storage for publication intents; must join the write transaction. */
  readonly outbox: OutboxBackend;
  readonly retention?: OutboxRetention;
  /** Expected durable publications per second; see `OutboxDefinition.expectedRatePerSecond`. */
  readonly expectedRatePerSecond?: number;
}

/**
 * The module a consumer mounts once. It owns the publication intent storage,
 * the dispatcher, its dead-letter operations, the cleanup operation and the
 * channel publisher providers for every listed channel, so a consumer only
 * declares `publishes` and binds `channel.publication`.
 *
 * Every module containing an operation that binds a listed channel's
 * publication must import {@link REALTIME_PUBLICATION_MODULE_ID}. Do not
 * also provide `channelPublisherProvider()` for a listed channel elsewhere.
 */
export function defineRealtimePublicationModule(options: RealtimePublicationModuleOptions) {
  const outbox = defineRealtimePublicationOutbox(options.channels, {
    ...(options.retention ? { retention: options.retention } : {}),
    ...(options.expectedRatePerSecond !== undefined
      ? { expectedRatePerSecond: options.expectedRatePerSecond }
      : {}),
  });
  const dispatcher = defineRealtimePublicationDispatcher(outbox, options);
  const cleanup = defineOutboxCleanup(outbox, options.clock ? { clock: options.clock } : {});
  const publishers = createChannelPublisherRegistry(options.channels, options.realtime);
  const module = defineModule({
    id: REALTIME_PUBLICATION_MODULE_ID,
    operations: [...dispatcher.operations, cleanup],
    providers: [valueProvider(outbox.writer, options.outbox), ...publishers.providers],
    imports: [],
    exports: [outbox.writer, ...publishers.channels.map((channel) => channel.publication)],
  });
  // Keep the module's own (named) type and intersect the registry, so the
  // consumer's declaration emit references ShipModule<...> instead of
  // expanding a spread of every operation and provider.
  return Object.freeze({ ...module, publishers }) as typeof module & {
    readonly publishers: ChannelPublisherRegistry;
  };
}

/**
 * The mounted `ship-realtime` module plus the publisher registry it bound.
 * `publishers` holds the same immediate publishers the module provides, so a
 * call site outside the kernel publishes through the backend the module was
 * composed with instead of building a channel-to-token map by hand.
 */
export type RealtimePublicationModule = ReturnType<typeof defineRealtimePublicationModule>;

