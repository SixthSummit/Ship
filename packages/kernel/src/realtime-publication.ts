export type RealtimePublicationRunnerPass = OutboxDispatchRunnerPass;

/** Instrumentation seam; `@sixthsummit/ship-realtime-socketio` provides an OpenTelemetry implementation. */
export type RealtimePublicationRunnerObserver = OutboxDispatchRunnerObserver;

export interface RealtimePublicationRunnerOptions
  extends DispatchRealtimePublicationsOptions,
    Omit<OutboxDispatchRunnerOptions, keyof DispatchOutboxOptions> {}

export interface RealtimePublicationRunner extends OutboxDispatchLoop {
  readonly kind: "ship.realtime-publication-runner";
}

/**
 * Framework-owned dispatcher loop for consumers that have not adopted the
 * jobs capability: the shared adaptive outbox loop
 * ({@link startOutboxDispatchRunner}) driving
 * `ship-realtime.publication.dispatch`. A full pass is followed by another at
 * once (at most `maxPassesPerCycle` back to back), a short or empty pass
 * waits `intervalMs`, a failed pass backs off, and `stop()` returns after the
 * in-flight pass. It needs nothing beyond an executor over an application
 * that mounts {@link defineRealtimePublicationModule}. Run one per process;
 * the outbox lease keeps several processes from dispatching the same record
 * twice.
 */
export function startRealtimePublicationRunner(
  executor: AnyExecutor,
  options: RealtimePublicationRunnerOptions = {},
): RealtimePublicationRunner {
  const loop = createOutboxDispatchLoop({
    executor,
    options,
    invalid: (message) =>
      new RealtimeError(
        "SHIP_REALTIME_RUNNER_INVALID",
        message.replace("dispatch runner", "realtime publication runner"),
      ),
    pass: (dispatchOptions) => dispatchRealtimePublications(executor, dispatchOptions),
  });
  return Object.freeze({
    kind: "ship.realtime-publication-runner" as const,
    get running() {
      return loop.running;
    },
    get passes() {
      return loop.passes;
    },
    runOnce: loop.runOnce,
    stop: loop.stop,
  });
}

export interface RealtimePublicationDispatchJobOptions {
  /** Defaults to `ship-realtime.publication.dispatch-job`; must be namespaced by the module that owns it. */
  readonly id?: string;
  readonly trigger: JobIntervalTrigger | JobScheduleTrigger;
  /**
   * Resolves the executor the job dispatches through. The executor is created
   * from the compiled application, after this job is declared, so it is read
   * lazily on every run.
   */
  readonly executor: () => AnyExecutor;
  /** Lock lease for the single runner; defaults to 60 s. */
  readonly leaseMs?: number;
}

const dispatchJobInputSchema = objectSchema({});

/**
 * The jobs-backed runner: a declared single-runner job whose every run is one
 * call of {@link dispatchRealtimePublications}, so the job backend's schedule,
 * lease and liveness replace the standalone loop without changing how a
 * publication is delivered. Compose it into a module whose id prefixes the
 * job id (by default `ship-realtime`, beside the publication module's
 * operations) and start it with `startJobRuntime`.
 */
export function defineRealtimePublicationDispatchJob(
  options: RealtimePublicationDispatchJobOptions,
) {
  if (typeof options?.executor !== "function") {
    throw new RealtimeError(
      "SHIP_REALTIME_RUNNER_INVALID",
      "defineRealtimePublicationDispatchJob requires an executor() thunk",
    );
  }
  return defineJob({
    id: options.id ?? `${REALTIME_PUBLICATION_OUTBOX_ID}.dispatch-job`,
    input: dispatchJobInputSchema,
    trigger: options.trigger,
    concurrency: {
      mode: "single-runner",
      key: () => "dispatch",
      ...(options.leaseMs !== undefined ? { leaseMs: options.leaseMs } : {}),
    },
    retry: { attempts: 1, backoff: DEFAULT_OUTBOX_RUNNER_BACKOFF },
    transaction: "none",
    dependencies: {},
    handler: ({ context }) =>
      dispatchRealtimePublications(options.executor(), {
        actor: context.actor,
        requestId: context.requestId,
        ...(context.signal ? { signal: context.signal } : {}),
      }),
  });
}
