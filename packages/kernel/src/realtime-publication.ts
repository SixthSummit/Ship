/**
 * @internal Binds one channel to the publication outbox writer of the active
 * write transaction. Scope and payload are validated exactly as on the
 * immediate path; the validated result is recorded as an intent keyed by the
 * channel id, and published by the dispatcher after commit.
 */
export function createOutboxChannelPublisher<TChannel extends AnyChannel>(
  channel: TChannel,
  writer: OutboxWriter<RealtimePublicationIntents>,
): ChannelPublisher<TChannel> {
  if (!isChannel(channel)) {
    throw new RealtimeError(
      "SHIP_REALTIME_CHANNEL_INVALID",
      "createOutboxChannelPublisher requires a channel created by defineChannel()",
    );
  }
  return Object.freeze({
    kind: "ship.channel-publisher" as const,
    channel,
    publish: async (
      scope: ChannelScopeInput<TChannel>,
      payload: unknown,
      options: ChannelPublishOptions = {},
    ): Promise<void> => {
      const scopeKey = channelScopeKey(channel, scope);
      const value = await validateChannelPayload(channel, payload);
      await writer.enqueue(
        channel.id,
        { scopeKey, payload: value },
        options.dedupeKey === undefined ? {} : { dedupeKey: options.dedupeKey },
      );
    },
  });
}

/**
 * @internal Finds the mounted publication outbox through its writer provider.
 * The outbox is application-specific (one intent per channel) while its id is
 * fixed, so the executor reads it from the compiled provider graph.
 */
export function findRealtimePublicationOutbox(
  app: CompiledApplication<string, readonly AnyModule[]>,
): AnyOutbox | undefined {
  const provider = Reflect.get(app.providerById, REALTIME_PUBLICATION_OUTBOX_ID) as
    | AnyProvider
    | undefined;
  const token = provider?.token;
  return token && isOutboxDependencyToken(token) && token.role === "writer"
    ? token.outbox
    : undefined;
}

