import { mkdir, rename, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { projectOpenApi } from "@sixthsummit/ship-contract/openapi";
import { projectClientContract } from "@sixthsummit/ship-contract/project";
import { GraphCliError, loadApplication } from "./graph.js";

/**
 * @typedef {object} ContractCliOptions
 * @property {string=} cwd
 * @property {string=} appPath
 * @property {string=} out
 * @property {string=} openapi
 * @property {string=} typescript
 * @property {string=} title
 * @property {string=} version
 * @property {string=} description
 * @property {readonly string[]=} serverUrls
 */
/**
 * @typedef {object} ContractArtifactResult
 * @property {"contract"} command
 * @property {true} ok
 * @property {string} appId
 * @property {`sha256:${string}`} fingerprint
 * @property {number} operations
 * @property {string} contract
 * @property {string} openapi
 * @property {string} typescript
 */

const DEFAULT_CONTRACT_PATH = ".ship/contract.json";
const DEFAULT_OPENAPI_PATH = ".ship/openapi.json";
const DEFAULT_TYPESCRIPT_PATH = ".ship/contract.ts";

/**
 * @param {ContractCliOptions} [options]
 * @returns {Promise<Readonly<ContractArtifactResult>>}
 */
export async function generateContractArtifacts(options = {}) {
  const cwd = resolve(options.cwd ?? process.cwd());
  const application = await loadApplication(options);
  const contract = projectClientContract(application);
  const openapi = projectOpenApi(application, {
    title: options.title?.trim() || application.id,
    version: options.version?.trim() || "0.0.0",
    ...(options.description ? { description: options.description } : {}),
    ...(options.serverUrls ? { serverUrls: options.serverUrls } : {}),
  });
  const contractPath = resolve(cwd, options.out ?? DEFAULT_CONTRACT_PATH);
  const openapiPath = resolve(cwd, options.openapi ?? DEFAULT_OPENAPI_PATH);
  const typescriptPath = resolve(cwd, options.typescript ?? DEFAULT_TYPESCRIPT_PATH);
  if (new Set([contractPath, openapiPath, typescriptPath]).size !== 3) {
    throw new GraphCliError([
      {
        code: "SHIP_CLI_CONTRACT_OUTPUT_COLLISION",
        severity: "error",
        message: "client contract, TypeScript contract, and OpenAPI outputs must be distinct",
        hint: "Pass distinct --out, --typescript, and --openapi paths.",
        path: [contractPath, typescriptPath, openapiPath].find(
          (path, index, paths) => paths.indexOf(path) !== index,
        ),
      },
    ]);
  }

  await writeStableJson(contractPath, contract);
  await writeStableJson(openapiPath, openapi);
  await writeStableText(typescriptPath, renderTypeScriptContract(contract));

  return Object.freeze({
    command: "contract",
    ok: true,
    appId: application.id,
    fingerprint: contract.fingerprint,
    operations: contract.operations.length,
    contract: contractPath,
    openapi: openapiPath,
    typescript: typescriptPath,
  });
}

function renderTypeScriptContract(contract) {
  return [
    "// Generated by `ship-api contract`. Do not edit by hand.",
    'import type { ClientContract, ClientTypeContract } from "@sixthsummit/ship-contract";',
    "",
    `export const clientContract = ${JSON.stringify(contract, null, 2)} as const satisfies ClientContract;`,
    "",
    "export type AppContract = ClientTypeContract<typeof clientContract>;",
    "",
  ].join("\n");
}

async function writeStableJson(target, value) {
  await writeStableText(target, `${JSON.stringify(value, null, 2)}\n`);
}

async function writeStableText(target, value) {
  const temporary = `${target}.${process.pid}.tmp`;
  await mkdir(dirname(target), { recursive: true });
  try {
    await writeFile(temporary, value, { flag: "wx" });
    await rename(temporary, target);
  } finally {
    await rm(temporary, { force: true });
  }
}
